/**
 * 2028年4月施行の遺族年金改正（言い方も判定も、ここ1か所に置く）
 *
 * **同じ改正を場所によって違う言い方で書かない。**
 * 失業カードの前提（`params.vintage`）、死亡詳細 STEP2 のことばの説明、
 * 世帯ごとの該当判定が、別々の文言を持っていた。読者には**別の話に見える**。
 *
 * **判定は「子の有無」ではなく「配偶者の生年コホート」で行う**（2026-09-21 修正）。
 * それ以前は「5年有期化の対象は子のいない配偶者 → お子さんがいるので直撃しません」と書いていたが、
 * **子がいることは末子が18歳になるまでの猶予にしかならない**。
 * 子が育ったあとに効くかどうかは、施行時点の年齢で決まる。
 *
 * 一次情報（2026-09-21 確認・厚生労働省「遺族厚生年金の見直しについて」
 * https://www.mhlw.go.jp/stf/seisakunitsuite/bunya/0000147284_00020.html ）：
 * 女性で影響を受けるのは**18歳年度末までの子がいない、2028年度末時点で40歳未満**の人。
 * **2028年度に40歳以上になる女性は現行どおり**（経過措置）。
 *
 * この取り違えは「1世帯で正しく見えるテンプレートが、隣の世帯で嘘になる」型である。
 * 配偶者38歳（2028年度に40歳）の世帯では旧ロジックでも結果が正しく、
 * **配偶者35歳の世帯に通したときだけ嘘になる**。だから両コホートをテストで固定する。
 */

/** 施行年度。2028年度＝2028-04-01〜2029-03-31 */
const REFORM_FISCAL_YEAR = 2028;
/** 経過措置の境目。2028年度に**この年齢以上**なら現行どおり */
const GRANDFATHER_AGE = 40;

/** 改正の呼び名。単独で読んで何の話か分かるところまで含める */
export const REFORM_2028 =
  "2028年4月施行の遺族年金改正（子のいない配偶者の5年有期化・中高齢寡婦加算の段階的廃止）";

/**
 * 「まだ反映していない」と言うときの型。
 *
 * **単独で読む場所（失業カードの前提）用にフルネームを含む。**
 * すでに改正の名前が出ている文の後ろに足すときは `REFORM_2028_NOT_APPLIED_TAIL` を使う
 * ── 同じ括弧つきの長い名前が1つの注記に2回出ると、読みにくいだけでなく別の話に見える。
 */
export const REFORM_2028_NOT_APPLIED = `${REFORM_2028}は反映していません。`;

/** 改正の名前を既に出している文の後ろに足す一言 */
export const REFORM_2028_NOT_APPLIED_TAIL = "なお、この試算はまだ改正前の制度で計算しています。";

export interface Reform2028 {
  /** この世帯の遺された配偶者が、改正の影響を受けるコホートか */
  applicable: boolean;
  reason: string;
}

/**
 * 2028年度時点の年齢から、経過措置に入るかを判定する。
 *
 * **年単位の近似**：`診断時の年齢 + (2028 − 診断年)`。
 * 誕生日と年度の境目で1歳ぶんずれうるが、この診断は全体を年単位で扱っており、
 * ここだけ日付精度にすると他と食い違う。境目の世帯には文面でそう書く。
 */
export function reform2028(input: {
  /** 遺される配偶者の現在年齢。配偶者がいなければ null */
  survivorAge: number | null;
  /** 診断の基準年（西暦） */
  asOfYear: number;
  hasChildren: boolean;
}): Reform2028 {
  const { survivorAge, asOfYear, hasChildren } = input;

  if (survivorAge === null) {
    return {
      applicable: false,
      reason:
        "遺族厚生年金の受け取り方の見直しは、遺された配偶者に関わるものです。この診断では配偶者がいないため、該当しません。",
    };
  }

  const ageIn2028 = survivorAge + (REFORM_FISCAL_YEAR - asOfYear);
  const grandfathered = ageIn2028 >= GRANDFATHER_AGE;

  // **「対象は子のいない配偶者」だけでは足りない。** 女性は生年でも分かれる
  /**
   * **男女で向きが逆なので、両方書く。**
   * 女性は制限方向（40歳未満に5年有期化）、男性は**拡大方向**
   * （いまは受け取れない層が、改正後は受け取れるようになる）。
   * この診断は**性別をうかがっていない**ので、どちらに当たるかは判定していないとはっきり書く。
   */
  const head =
    "5年有期化の対象になるのは、18歳年度末までのお子さんがいない配偶者です。女性の場合はさらに生年で分かれ、2028年度に40歳以上になる方は現行どおりです。男性の場合は逆に、いまは受け取れない方が改正後は受け取れるようになります（60歳未満で18歳年度末までのお子さんがいない方が新たに対象）。この診断では性別をうかがっていないため、以下は女性の場合の見立てです。";

  if (grandfathered) {
    return {
      applicable: false,
      reason: `${head}この診断の配偶者は2028年度に${ageIn2028}歳になるため、お子さんが独立したあとも当面これまで通りです。`,
    };
  }

  return {
    applicable: true,
    reason: hasChildren
      ? `${head}この診断の配偶者は2028年度に${ageIn2028}歳で、40歳未満の区分に入ります。お子さんが18歳の年度末を超えたあとは、受け取り方が変わる可能性があります（5年の有期給付・中高齢寡婦加算の縮小）。`
      : `${head}この診断の配偶者は2028年度に${ageIn2028}歳で、40歳未満の区分に入ります。お子さんがいないため、受け取り方が変わる可能性があります（5年の有期給付・中高齢寡婦加算の縮小）。`,
  };
}
