/**
 * 台帳の丸め（表示層）
 *
 * **台帳は読者が縦に足して確かめる形式**なので、
 * **画面に出ている数どうしで検算が通らなければならない**。
 *
 * 各行を正確な値から丸め、合計は正確な値から別に丸める、という作り方をすると、
 * 丸め誤差が積もって**行の和と合計がずれる**。2026-09-21、実際に
 * `11.1 + 6.0 + 13.3 = 30.4` なのに計が `30.5`、差し引きも 0.1 ずれていた。
 *
 * 解決は単純で、**合計も差し引きも、丸めたあとの数から作る**。
 * 金額を作っているのではなく、**表示単位（0.1万円）に揃えているだけ**である
 * （CLAUDE.md「金額は円単位で扱い、表示のときだけ万円に変換する」の範囲内）。
 */

const MONTHS = 12;
/** 表示の刻み。0.1万円＝1,000円 */
const STEP = 1000;

/** 円/年 → 表示単位（0.1万円）に丸めた 円/月 */
export function toMonthlyDisplay(yenPerYear: number): number {
  return Math.round(yenPerYear / MONTHS / STEP) * STEP;
}

/** 表示単位に丸めた円 → 「17.5」のような1桁の文字列（単位は呼び出し側） */
export function manDigits(yen: number): string {
  return (Math.abs(yen) / 10_000).toFixed(1);
}
